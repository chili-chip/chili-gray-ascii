#!/usr/bin/env python3
"""Turn story/teksty.csv and story/tropy.csv into C++ (texts_gen.hpp/.cpp).

    gen_texts.py STORY_DIR OUT_DIR

teksty.csv: id;who;pl;en. Ids ending in .<number> (halina1.1, halina1.2)
form a dialog group named by the part before the dot, in file order.
tropy.csv: id;pl_name;pl_note;en_name;en_note.
Lines starting with # are comments. Text is UTF-8 and stays UTF-8.
"""
import os
import re
import sys

WHO = ["-", "SZARY", "MYSL", "HALINA", "KUBA", "RYSIEK", "JASINSKI", "BOGDAN", "RADIO", "NARR"]


def rows(path, columns):
    out = []
    with open(path, encoding="utf-8") as f:
        header = True
        for n, line in enumerate(f, 1):
            line = line.rstrip("\n")
            if not line.strip() or line.startswith("#"):
                continue
            if header:
                header = False
                continue
            parts = line.split(";")
            if len(parts) != columns:
                sys.exit(f"{path}:{n}: expected {columns} columns, got {len(parts)}: {line}")
            out.append((n, [p.strip() for p in parts]))
    return out


def ident(s):
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    story, out = sys.argv[1], sys.argv[2]
    texts = rows(os.path.join(story, "teksty.csv"), 4)
    clues = rows(os.path.join(story, "tropy.csv"), 5)

    ids, groups = [], []  # groups: [name, first, count]
    seen = set()
    for n, (tid, who, pl, en) in texts:
        if tid in seen:
            sys.exit(f"teksty.csv:{n}: duplicate id {tid}")
        seen.add(tid)
        if who not in WHO:
            sys.exit(f"teksty.csv:{n}: unknown speaker {who}")
        m = re.fullmatch(r"(.+)\.(\d+)", tid)
        if m:
            g = m.group(1)
            if groups and groups[-1][0] == g:
                groups[-1][2] += 1
            elif any(x[0] == g for x in groups):
                sys.exit(f"teksty.csv:{n}: lines of group {g} must be together")
            else:
                groups.append([g, len(ids), 1])
        ids.append((tid, who, pl, en))

    hpp = ["// Generated by tools/gen_texts.py from story/*.csv. Do not edit.", "#pragma once", "#include <cstdint>", "",
           "namespace txt {", "enum Who : uint8_t {"]
    hpp += [f"    W_{w if w != '-' else 'NONE'}," for w in WHO]
    hpp += ["};", "enum Id : uint16_t {"]
    hpp += [f"    {ident(t[0])}," for t in ids]
    hpp += ["    COUNT", "};", "enum Group : uint16_t {"]
    hpp += [f"    G_{ident(g[0])}," for g in groups]
    hpp += ["    GROUP_COUNT", "};",
            "struct Range { uint16_t first, count; };",
            "extern const char *const text[COUNT][2];",
            "extern const uint8_t who[COUNT];",
            "extern const Range groups[GROUP_COUNT];",
            "}  // namespace txt", "",
            "namespace clue {", "enum Id : uint8_t {"]
    hpp += [f"    {ident(c[1][0])}," for c in clues]
    hpp += ["    COUNT", "};",
            "extern const char *const name[COUNT][2];",
            "extern const char *const note[COUNT][2];",
            "}  // namespace clue", ""]

    cpp = ["// Generated by tools/gen_texts.py from story/*.csv. Do not edit.", '#include "texts_gen.hpp"', "",
           "namespace txt {", "const char *const text[COUNT][2] = {"]
    cpp += [f"    {{{cstr(t[2])}, {cstr(t[3])}}}," for t in ids]
    cpp += ["};", "const uint8_t who[COUNT] = {"]
    cpp += [f"    W_{t[1] if t[1] != '-' else 'NONE'}," for t in ids]
    cpp += ["};", "const Range groups[GROUP_COUNT] = {"]
    cpp += [f"    {{{g[1]}, {g[2]}}},  // {g[0]}" for g in groups]
    cpp += ["};", "}  // namespace txt", "", "namespace clue {", "const char *const name[COUNT][2] = {"]
    cpp += [f"    {{{cstr(c[1][1])}, {cstr(c[1][3])}}}," for c in clues]
    cpp += ["};", "const char *const note[COUNT][2] = {"]
    cpp += [f"    {{{cstr(c[1][2])}, {cstr(c[1][4])}}}," for c in clues]
    cpp += ["};", "}  // namespace clue", ""]

    os.makedirs(out, exist_ok=True)
    for name, lines in (("texts_gen.hpp", hpp), ("texts_gen.cpp", cpp)):
        path = os.path.join(out, name)
        data = "\n".join(lines)
        try:
            with open(path, encoding="utf-8") as f:
                if f.read() == data:
                    continue
        except OSError:
            pass
        with open(path, "w", encoding="utf-8") as f:
            f.write(data)


if __name__ == "__main__":
    main()
